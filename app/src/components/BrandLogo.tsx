/** 名称模糊匹配：命中关键子串就归到对应品牌。 */
const HINTS: [RegExp, string][] = [
  [/claude|anthropic/i, 'claude'],
  [/codex|openai/i, 'openai'],
  [/gemini/i, 'gemini'],
  [/vs\s?code|visual\s?studio/i, 'vscode'],
  [/copilot/i, 'copilot'],
  [/jetbrains/i, 'jetbrains'],
  [/cline/i, 'cline'],
  [/opencode/i, 'opencode'],
  [/cursor/i, 'cursor'],
  [/\bzed\b/i, 'zed'],
  [/mistral/i, 'mistral'],
  [/nvidia/i, 'nvidia'],
  [/openrouter/i, 'openrouter'],
  [/qwen/i, 'qwen'],
  [/deepseek/i, 'deepseek'],
  [/groq/i, 'groq'],
  [/cerebras/i, 'cerebras'],
];

export function monogram(name: string): string {
  const parts = name.split(/[\s_-]+/).filter(Boolean);
  if (parts.length >= 2) return (parts[0][0] + parts[1][0]).toUpperCase();
  return name.slice(0, 2).toUpperCase();
}

function resolve(id?: string, name?: string): { brand?: Brand; letters: string } {
  const letters = monogram(name || id || '??');
  if (id) {
    const key = KEYS[id.toLowerCase()];
    if (key && BRANDS[key]) return { brand: BRANDS[key], letters };
  }
  const hay = `${id ?? ''} ${name ?? ''}`;
  for (const [re, key] of HINTS) {
    if (re.test(hay) && BRANDS[key]) return { brand: BRANDS[key], letters };
  }
  return { letters };
}

/**
 * 品牌 Logo。
 * @param id    Agent / 厂商 id（如 `claude-code`、`groq`）
 * @param name  展示名（id 未知时用于模糊匹配与字母回落）
 * @param size  边长像素，默认 24
 */
export function BrandLogo({
  id,
  name,
  size = 24,
  className,
}: {
  id?: string;
  name?: string;
  size?: number;
  className?: string;
}) {
  const { brand, letters } = resolve(id, name);
  if (brand) {
    return (
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        className={className}
        role="img"
        aria-label={name ?? id}
        style={{ flex: 'none', display: 'block' }}
      >
        <path d={brand.d} fill={brand.color ?? 'currentColor'} />
      </svg>
    );
  }
  // 未收录品牌：字母回落，保持和旧版一样的方块观感
  return (
    <span
      className={className}
      style={{
        width: size,
        height: size,
        borderRadius: Math.max(4, size * 0.24),
        display: 'grid',
        placeItems: 'center',
        flex: 'none',
        fontSize: size * 0.38,
        fontWeight: 700,
        background: 'var(--panel-3)',
        color: 'var(--text-2)',
        letterSpacing: 0.5,
      }}
    >
      {letters}
    </span>
  );
}
